// Recover the original dialogue verbatim, including its selection directives.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const catalogs={},sources={};
for(const kind of ['schieber','differ']){
  const path=`original/${kind==='schieber'?'Schieber':'Differ'}/ResUtils.pas`;
  const bytes=await readFile(path),source=bytes.toString('latin1');
  const array=source.slice(source.indexOf('of TString = ('),source.indexOf('const gMaxRsrcInfo'));
  const groups={};let group;
  for(const match of array.matchAll(/'((?:[^']|'')*)'/g)){
    const line=match[1].replaceAll("''","'"),header=/^STR#=(\d+)/.exec(line);
    if(header){group=groups[Number(header[1])]=[];continue;}
    if(group&&/^\s*\d+\s/.test(line))group.push(line.slice(6));
  }
  if(Object.values(groups).flat().length<3000)throw new Error(`Incomplete ${kind} dialogue extraction`);
  catalogs[kind]=groups;sources[kind]={path,sha256:createHash('sha256').update(bytes).digest('hex')};
}
const shared=JSON.stringify(catalogs.schieber)===JSON.stringify(catalogs.differ);
await writeFile('src/commentaryData.js',`// Generated by scripts/prepare-commentary.mjs; do not edit.\nexport const sources=${JSON.stringify(sources)};\nconst schieber=${JSON.stringify(catalogs.schieber,null,2)};\nexport default {schieber,differ:${shared?'schieber':JSON.stringify(catalogs.differ,null,2)}};\n`);
console.log(`Recovered ${Object.values(catalogs.schieber).flat().length} Schieber and ${Object.values(catalogs.differ).flat().length} Differ lines (${shared?'shared':'separate'} catalogs).`);
