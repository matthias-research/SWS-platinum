import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {Game} from '../src/engine/game.js';
import {SchieberAI} from '../src/ai/schieber.js';
import {DifferAI} from '../src/ai/differ.js';

for(const kind of ['schieber','differ'])test(kind+': adaptive and fixed resolution resize drawing and clickable cards together',async({browser})=>{
  const context=await browser.newContext({viewport:{width:1100,height:800},deviceScaleFactor:2});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const ai=kind==='schieber'?new SchieberAI(await readFile('public/assets/ai/RUGD7000.DAT')):new DifferAI(await readFile('public/assets/ai/RGDIFF.DAT'));
  const game=new Game({kind,seed:37,id:'resolution-'+kind,rules:{fPointPlay:false,fRoundLimit:20,fSuitsEnabled:false}},ai);
  game.act({type:'deal'});
  while(!(game.request()?.player===3&&game.request().command==='cmdPlay'&&game.view().trick.fPlayed.filter(Boolean).length===3)){
    if(game.phase==='deal')game.act({type:'deal'});else if(game.pause)game.act({type:'continue'});else game.computer();
  }
  const saved={name:'resolution.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(game.save()))};
  await page.goto('/');await expect(page.getByRole('navigation')).toHaveCount(0);
  await page.locator('input[type=file]').setInputFiles(saved);
  const table=page.locator('.scene-frame > canvas');
  await expect(table).toHaveAttribute('data-ready','true');
  await expect(page.locator('.menu-title')).toHaveText(['Datei','Jass','Einstellungen','Browser','Hilfe']);
  await page.getByRole('button',{name:'Browser',exact:true}).click();
  await expect(page.locator('#menu-Browser .menu-item')).toHaveText(['Lowlevel menu',/Verbesserte Grafik$/,'Originalgrafik',/Adaptive resolution$/,'Fixed resolution']);
  await page.getByRole('button',{name:'Fixed resolution',exact:true}).click();
  await expect(table).toHaveAttribute('data-scale','1');
  await expect(table).toHaveAttribute('data-card-size','2');
  const firstSize=await table.boundingBox();
  expect(firstSize.height).toBe(740);
  const largeCard=await page.locator('.card-target').first().boundingBox();
  const portrait=await page.locator('.table-portrait[data-player="3"]').boundingBox();
  expect(portrait.width).toBe(56);
  await page.setViewportSize({width:1300,height:900});
  await expect.poll(async()=>(await table.boundingBox()).height).toBe(840);
  const moved=await page.locator('.table-portrait[data-player="3"]').boundingBox();
  expect(moved.width).toBe(56);expect(moved.y-portrait.y).toBe(50);
  expect((await page.locator('.card-target').first().boundingBox()).height).toBe(largeCard.height);
  expect(Number(await table.getAttribute('width'))).toBe(Math.round((await table.boundingBox()).width*2));
  await page.screenshot({path:'artifacts/browser/fixed-resolution-'+kind+'.png'});
  await page.setViewportSize({width:700,height:580});
  await expect(table).toHaveAttribute('data-card-size','1');
  await expect.poll(async()=>(await page.locator('.card-target').first().boundingBox()).height).toBeLessThan(largeCard.height);
  const card=game.request().data.fLegal.find(Boolean);
  await page.locator('.card-target[data-card-id="'+card+'"]').click();
  const clear=page.getByRole('button',{name:'Stich auf dem Tisch abräumen',exact:true});
  await expect(clear).toBeVisible();
  await page.screenshot({path:'artifacts/browser/fixed-resolution-small-'+kind+'.png'});
  await clear.click({position:{x:20,y:20}});await expect(clear).toHaveCount(0);
  await page.reload();await page.locator('input[type=file]').setInputFiles(saved);
  await expect(table).toHaveAttribute('data-resolution','fixed');
  await page.getByRole('button',{name:'Browser',exact:true}).click();
  await page.getByRole('button',{name:'Adaptive resolution',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await expect(table).toHaveAttribute('data-resolution','adaptive');
  await expect(table).toHaveAttribute('data-card-size','2');
  await expect.poll(async()=>(await table.boundingBox()).width).toBeLessThanOrEqual(374);
  const adapted=await table.boundingBox();expect(adapted.width/adapted.height).toBeCloseTo(768/528,2);
  expect(errors).toEqual([]);await context.close();
});
